import { readFileSync, writeFileSync } from "node:fs";

const file = process.argv[2];

if (!file) {
  throw new Error("Missing route tree path");
}

const source = readFileSync(file, "utf8");
const cleaned = source
  .replace(/\n\/\/ This file was automatically generated by TanStack Router\.\n\/\/ You should NOT make any changes in this file as it will be overwritten\.\n\/\/ Additionally, you should also exclude this file from your linter and\/or formatter to prevent it from being checked or modified\.\n/, "\n")
  .replace(/\n{3,}/g, "\n\n");

writeFileSync(file, cleaned);
